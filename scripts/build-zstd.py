"""Rebuild the bundled, import-free libzstd decoder from pinned upstream archives.

Ordinary npm builds use the committed generated module; they need no C toolchain.
This explicit maintenance command downloads and verifies the two source/toolchain
archives, compiles the official standalone decoder and writes its base64 module.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import subprocess
import tarfile
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARCHIVES = [
    (
        "zstd-1.5.7",
        "https://github.com/facebook/zstd/releases/download/v1.5.7/zstd-1.5.7.tar.gz",
        "eb33e51f49a15e023950cd7825ca74a4a2b43db8354825ac24fc1b7ee09e6fa3",
    ),
    (
        "wasi-sdk-27.0-x86_64-linux",
        "https://github.com/WebAssembly/wasi-sdk/releases/download/wasi-sdk-27/wasi-sdk-27.0-x86_64-linux.tar.gz",
        "b7d4d944c88503e4f21d84af07ac293e3440b1b6210bfd7fe78e0afd92c23bc2",
    ),
]
FLAGS = [
    "-O3",
    "-DNDEBUG",
    "-mexec-model=reactor",
    "-Wl,--export=ZSTD_decompress",
    "-Wl,--export=ZSTD_isError",
    "-Wl,--export=ZSTD_getErrorCode",
    "-Wl,--export=ZSTD_versionNumber",
    "-Wl,--export=malloc",
    "-Wl,--export=free",
    "-Wl,--strip-all",
    "-Wl,--initial-memory=2097152",
    "-Wl,--max-memory=134217728",
    "-Wl,-z,stack-size=1048576",
]
EXPECTED_WASM = "be026e8a9d0e89d7ad3045603636e81c7706a49e4d17674261c7b59fb2f43c97"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--cache", type=Path, default=ROOT / "studies/zstd-collector/cache/build"
    )
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    archives = []
    for name, url, digest in ARCHIVES:
        path = args.cache / (name + ".tar.gz")
        if not path.exists():
            with (
                urllib.request.urlopen(url, timeout=120) as response,
                path.open("wb") as output,
            ):
                while chunk := response.read(1024 * 1024):
                    output.write(chunk)
        assert sha(path.read_bytes()) == digest, f"Changed archive: {name}"
        archives.append(path)
    with tempfile.TemporaryDirectory(prefix="zstd-build-", dir=args.cache) as temporary:
        work = Path(temporary)
        for archive in archives:
            with tarfile.open(archive) as source:
                source.extractall(work, filter="data")
        source = work / ARCHIVES[0][0] / "build/single_file_libs"
        sdk = work / ARCHIVES[1][0]
        subprocess.run(
            ["sh", "create_single_file_decoder.sh"],
            cwd=source,
            check=True,
            stdout=subprocess.DEVNULL,
        )
        binary = work / "zstd.wasm"
        subprocess.run(
            [str(sdk / "bin/clang"), "zstddeclib.c", *FLAGS, "-o", str(binary)],
            cwd=source,
            check=True,
        )
        data = binary.read_bytes()
        assert sha(data) == EXPECTED_WASM, (
            "Decoder build differs from the retained artifact"
        )
        abi = json.loads(
            subprocess.check_output(
                [
                    "node",
                    "--input-type=module",
                    "-e",
                    """
import {readFileSync} from 'node:fs';
const module=new WebAssembly.Module(readFileSync(process.argv[1]));
const instance=new WebAssembly.Instance(module,{});instance.exports._initialize();
if(WebAssembly.Module.imports(module).length)throw Error('Unexpected host imports');
if(instance.exports.ZSTD_versionNumber()!==10507)throw Error('Unexpected libzstd version');
try{instance.exports.memory.grow(2048);throw Error('Missing memory cap');}catch(e){if(!(e instanceof RangeError))throw e;}
console.log(JSON.stringify({imports:WebAssembly.Module.imports(module),exports:WebAssembly.Module.exports(module),version:instance.exports.ZSTD_versionNumber()}));
""",
                    str(binary),
                ],
                text=True,
            )
        )
    target = ROOT / "src/core/vendor/zstd-wasm.ts"
    target.parent.mkdir(exist_ok=True)
    target.write_text(
        '// Generated by scripts/build-zstd.py; libzstd 1.5.7 (BSD-3-Clause).\n// Linked WASI/LLVM notices: LICENSE-WASI. No host imports.\nexport const ZSTD_WASM_BASE64 = "'
        + base64.b64encode(data).decode()
        + '";\n'
    )
    manifest = {
        "version": "libzstd 1.5.7",
        "bytes": len(data),
        "sha256": sha(data),
        "wasmMaximumBytes": 134217728,
        "archives": [{"url": url, "sha256": digest} for _, url, digest in ARCHIVES],
        "compilerFlags": FLAGS,
        "abi": abi,
    }
    (ROOT / "scripts/zstd/decoder.json").write_text(
        json.dumps(manifest, indent=2) + "\n"
    )
    print(
        json.dumps(
            {
                "bytes": len(data),
                "sha256": sha(data),
                "hostImports": len(abi["imports"]),
                "version": abi["version"],
            }
        )
    )


if __name__ == "__main__":
    main()
